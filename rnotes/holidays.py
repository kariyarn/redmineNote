"""대한민국 공휴일(대체공휴일 포함) 표와 '쉬는 날' 판단. 알림은 기간 메모의 주말·공휴일을 건너뛴다.
내장 표는 2026~2028년이다. 그 밖의 연도나 임시공휴일은 설정의 `holiday_extra`(날짜를 쉼표로 구분)에 적어 넣는다."""
import datetime
import re

HOLIDAYS = frozenset("""
2026-01-01 2026-02-16 2026-02-17 2026-02-18 2026-03-01 2026-03-02 2026-05-05 2026-05-24 2026-05-25 2026-06-03 2026-06-06
2026-08-15 2026-08-17 2026-09-24 2026-09-25 2026-09-26 2026-10-03 2026-10-05 2026-10-09 2026-12-25
2027-01-01 2027-02-05 2027-02-06 2027-02-07 2027-02-08 2027-03-01 2027-05-05 2027-05-13 2027-06-06 2027-08-15 2027-08-16
2027-09-14 2027-09-15 2027-09-16 2027-10-03 2027-10-04 2027-10-09 2027-10-11 2027-12-25 2027-12-27
2028-01-01 2028-01-25 2028-01-26 2028-01-27 2028-03-01 2028-04-12 2028-05-02 2028-05-05 2028-06-06 2028-08-15
2028-10-02 2028-10-03 2028-10-04 2028-10-05 2028-10-09 2028-12-25
""".split())


def extra_days(setting_value):
    """설정에 적은 추가 휴일(2026-10-02, 2026-12-31 …)을 집합으로."""
    return {d for d in re.findall(r"\d{4}-\d{2}-\d{2}", setting_value or "")}


def holiday_dates(year, extra=()):
    """그 해의 공휴일 날짜 목록(주말은 포함하지 않음)."""
    p = f"{int(year):04d}-"
    return sorted(d for d in (set(HOLIDAYS) | set(extra)) if d.startswith(p))


def is_off_day(date_str, extra=()):
    """토 · 일 · 공휴일이면 True."""
    d = datetime.date.fromisoformat(date_str)
    return d.weekday() >= 5 or date_str in HOLIDAYS or date_str in extra
